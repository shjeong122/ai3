package P677;

public class Score {
	public int hakbun;
	public int score;

	public Score(int hakbun, int score) {
		super();
		this.hakbun = hakbun;
		this.score = score;
	}

	public int getHakbun() {
		return hakbun;
	}

	public void setHakbun(int hakbun) {
		this.hakbun = hakbun;
	}

	public int getScore() {
		return score;
	}

	public void setScore(int score) {
		this.score = score;
	}

}
